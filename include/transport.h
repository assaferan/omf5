#ifndef __TRANSPORT_H__
#define __TRANSPORT_H__

#include "genus.h"
#include "tq_table.h"
#include "typedefs.h"

// The memory of T_p with transport for each of the p^3 + p^2 + p + 1 isotropic lines mod p, in bits: 1
// for the bitmap of the lines reached at an odd p, so it grows as p^3 / 8 bytes. At p = 2, and when the
// Gram matrix of a class is degenerate mod p, the bitmap takes 2 bits a line, and when it has no diagonal
// entry prime to p, its lines are kept in a hash set instead, of up to 32 bytes a line (8 bytes a slot, at
// most half of the slots used, rounded to a power of 2). -transport=M bounds it by M MB (256 by default):
// the primes p for which it would need more use the orbits and the neighbors instead, and so do the
// columns of the classes whose 2-bit bitmap or hash set would not fit.
#define TRANSPORT_BITS_PER_LINE 1
#define TRANSPORT_BITS_PER_LINE_HASH 256
#define TRANSPORT_DEFAULT_MEMORY_MB 256

// Sets the bound, in MB, on the memory of the set of the lines seen.
void hecke_transport_set_memory(slong mb);

// Whether the set of the lines of p fits in the bound.
bool hecke_transport_fits(int p);

// The largest prime p which fits in the bound.
int hecke_transport_max_prime(void);

// The column of the class gen_idx of T_p for every conductor, as hecke_col_all_conductors, but counted:
// hist[(class << num_primes) | spinor bits] is incremented for each p-neighbor of the class gen_idx, so
// hist has num_classes << num_primes entries, which the caller zeroes. Only one neighbor in each orbit of
// the group generated by the automorphisms of the class and the isometries g = T->isom[gen_idx][w] with
// T->cls[gen_idx][w] = gen_idx is tested for isometry; the class and an isometry of the others are carried
// along the generators with the table T of T_q (usually: when the stack is full, an orbit can need more
// tests). Needs T->q != p. With k = 2 it is the column of T_{p^2}, over the p^2-neighbors of nbr_data,
// which are kept by their lattices (p N mod p^3 L, in Hermite normal form) in a hash set.
// Returns the number of neighbors, or -1 when the lines (or the p^2-neighbors) of the class do not fit in
// the memory bound (then nothing is computed, and the column is to be computed without the table).
slong hecke_col_all_conductors_transport(slong* hist, int p, int k, int gen_idx, const genus_t genus,
					 const tq_table_t T);

#endif // __TRANSPORT_H__

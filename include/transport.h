#ifndef __TRANSPORT_H__
#define __TRANSPORT_H__

#include "genus.h"
#include "tq_table.h"
#include "typedefs.h"

// The same as hecke_col_all_conductors: one entry (class << num_primes) | spinor bits of spin_vals for
// each p-neighbor of the class gen_idx, with the same Hecke matrices for every conductor. Only one
// neighbor in each orbit of the group generated by the automorphisms of the class and the isometries
// g = T->isom[gen_idx][w] with T->cls[gen_idx][w] = gen_idx is tested for isometry; the class and an
// isometry of the others are carried along the generators with the table T of T_q. Needs T->q != p.
// Returns the number of entries.
slong hecke_col_all_conductors_transport(W64* spin_vals, int p, int gen_idx, const genus_t genus,
					 const tq_table_t T);

#endif // __TRANSPORT_H__
